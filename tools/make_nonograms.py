"""Checks every picture in nonogram_art.py and writes
Puzzles/Nonograms/Engine/NonogramLibrary.swift.

Run from the tools folder:  python3 make_nonograms.py
"""
import os
from nonogram_art import SMALL, MEDIUM, LARGE, LESSON_PUZZLE
from nonogram_reference import parse, line_solvable

OUT = os.path.join(os.path.dirname(__file__), '..', 'Puzzles', 'Nonograms', 'Engine', 'NonogramLibrary.swift')


def check(group, size):
    for pid, name, art in group:
        g = parse(art)
        assert len(g) == size and all(len(r) == size for r in g), pid
        assert line_solvable(g), f'{pid} needs guessing; adjust the picture'


def swift_list(group):
    out = []
    for pid, name, art in group:
        rows = ',\n'.join(f'            "{l.strip()}"' for l in art.strip().splitlines())
        out.append(f'        NonogramPuzzle(id: "{pid}", name: "{name}", art: [\n{rows}\n        ])')
    return ',\n'.join(out)


def main():
    check(SMALL, 5)
    check(MEDIUM, 10)
    check(LARGE, 15)
    check([LESSON_PUZZLE], 5)
    src = f'''// Generated by tools/make_nonograms.py from tools/nonogram_art.py. Don't edit by hand.
// Every picture is original and can be solved one line at a time, with no guessing.

enum NonogramLibrary {{
    static let small: [NonogramPuzzle] = [
{swift_list(SMALL)}
    ]

    static let medium: [NonogramPuzzle] = [
{swift_list(MEDIUM)}
    ]

    static let large: [NonogramPuzzle] = [
{swift_list(LARGE)}
    ]

    /// The practice puzzle from the How to Play lesson.
    static let starter = {swift_list([LESSON_PUZZLE]).strip()}
}}
'''
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w') as f:
        f.write(src)
    print('wrote', os.path.normpath(OUT))


if __name__ == '__main__':
    main()
